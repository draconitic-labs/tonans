#[cfg(test)]
mod tests {
    use super::*;

    fn now() -> DateTime<Utc> {
        DateTime::from_timestamp(1_767_225_600, 0).expect("a valid instant")
    }

    #[test]
    fn the_demo_project_survives_the_real_importer_and_validates() {
        // If this fails, a first launch fails, and it fails in the one place a new
        // user has no way to work around.
        let project = build(now()).expect("the bundled demo must import and validate");
        let dataset = project.dataset.as_ref().unwrap();

        assert_eq!(
            dataset.interval_count, 8_760,
            "the demo must be a full year of hourly data"
        );
        assert_eq!(dataset.interval_minutes, 60);
        assert_eq!(
            dataset.synthesized_interval_count, 0,
            "the demo data has no gaps"
        );
        assert_eq!(project.scenarios.len(), 3);
        assert!(project.scenario("baseline").unwrap().battery.is_none());
        assert!(project
            .scenario("self-consumption")
            .unwrap()
            .battery
            .is_some());
    }

    #[test]
    fn the_demo_fits_inside_the_evaluation_entitlement() {
        // The demo is what an evaluation user sees first. If it exceeded the tier's
        // own limits it could not be run.
        let project = build(now()).unwrap();
        let entitlements = tonans_core::licensing::Entitlements::evaluation();
        entitlements
            .check_scenario_count(project.scenarios.len())
            .expect("the demo must be runnable on the shipped tier");
    }

    #[test]
    fn the_demo_declares_itself_synthetic() {
        // The single most damaging thing this application could do is present invented
        // data as a real building's.
        let project = build(now()).unwrap();
        assert!(project.notes.contains("SYNTHETIC"), "{}", project.notes);
        assert!(project.notes.contains("not a real site"));
    }

    #[test]
    fn every_demo_series_was_imported() {
        let project = build(now()).unwrap();
        let dataset = project.dataset.as_ref().unwrap();
        for kind in [
            SeriesKind::Load,
            SeriesKind::CriticalLoad,
            SeriesKind::Generation,
            SeriesKind::ImportPrice,
            SeriesKind::ExportPrice,
            SeriesKind::Temperature,
        ] {
            assert!(
                dataset.series.contains_key(&kind),
                "{} is missing",
                kind.as_str()
            );
        }
        let periods = dataset.demand_periods.as_ref().expect("demand periods");
        assert_eq!(periods.labels.len(), 2);
    }
}
