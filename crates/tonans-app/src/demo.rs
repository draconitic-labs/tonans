//! The bundled demonstration project.
//!
//! Installed on first launch so that a new user has something to open. It is built
//! by feeding an embedded CSV through the *real* importer — not by constructing a
//! `Dataset` directly — which means the demo is proof that the import path works,
//! and it cannot drift away from what a user's own file would have to survive.
//!
//! The data is **synthetic and Tonans says so, on the project and in every report
//! made from it.** It is not a real site's meter export. Presenting invented data
//! as a real building's would be the most damaging thing this application could do.

use std::collections::BTreeMap;

use chrono::{DateTime, Utc};
use tonans_core::csvimport::{self, ColumnMapping, ImportRequest, ImportUnit, MappedColumn};
use tonans_core::error::Result;
use tonans_core::schema::{
    BatterySpec, BenefitScaling, DegradationSpec, DispatchPolicy, EconomicsSpec, GapPolicy,
    InverterSpec, OutageSpec, OutageWindow, Project, RateSource, ReplacementSpec, Scenario,
    SeriesKind, Site, TariffSpec, TemperatureDerate, TemperatureDeratePoint,
};
use tonans_core::store::Workspace;

use crate::clock;
use crate::state::DEMO_PROJECT_NAME;

/// A synthetic year of hourly data for a light-industrial site.
const DEMO_CSV: &str = include_str!("../../../samples/riverside-works-2024.csv");

/// The site's timezone. Naive timestamps in the CSV would be read in this zone; the
/// sample carries explicit offsets, so they are not.
const DEMO_TIMEZONE: &str = "America/New_York";

/// Install the demonstration project if it is not already there.
///
/// Never overwrites: a user may have edited the demo, and their edits are theirs.
pub fn ensure_installed(workspace: &Workspace) -> Result<()> {
    if workspace.project_exists(DEMO_PROJECT_NAME)? {
        return Ok(());
    }
    let project = build(clock::now_utc())?;
    workspace.save_project(&project)?;
    Ok(())
}

/// Build the demonstration project from the embedded CSV.
///
/// Public so the end-to-end tests can build it without touching a workspace.
pub fn build(now: DateTime<Utc>) -> Result<Project> {
    let mut project = Project::new(
        "demo-riverside-works",
        DEMO_PROJECT_NAME,
        Site {
            timezone: DEMO_TIMEZONE.to_string(),
            currency: "USD".to_string(),
        },
        now,
    )?;

    project.notes = "SYNTHETIC DEMONSTRATION DATA. This is not a real site's meter export. It was \
         generated by `cargo run --example generate_demo_csv` and exists so that Tonans has \
         something to open on a first launch. Every number derived from it is an illustration of \
         the model, not a finding about a building."
        .to_string();

    let report = csvimport::import(DEMO_CSV.as_bytes(), &import_request(), now)?;
    project.dataset = Some(report.dataset);

    project.scenarios = vec![baseline(), self_consumption(), peak_limit()];
    project.baseline_scenario_id = "baseline".to_string();

    // If the demo does not validate, the demo is a bug, and shipping it would mean
    // shipping a first-launch experience that fails.
    project.validate_runnable()?;
    Ok(project)
}

fn import_request() -> ImportRequest {
    let mut series = BTreeMap::new();
    series.insert(
        SeriesKind::Load,
        MappedColumn {
            header: "load_kw".to_string(),
            unit: ImportUnit::Kilowatt,
        },
    );
    series.insert(
        SeriesKind::CriticalLoad,
        MappedColumn {
            header: "critical_load_kw".to_string(),
            unit: ImportUnit::Kilowatt,
        },
    );
    series.insert(
        SeriesKind::Generation,
        MappedColumn {
            header: "pv_kw".to_string(),
            unit: ImportUnit::Kilowatt,
        },
    );
    series.insert(
        SeriesKind::ImportPrice,
        MappedColumn {
            header: "import_price_per_kwh".to_string(),
            unit: ImportUnit::UsdPerKilowattHour,
        },
    );
    series.insert(
        SeriesKind::ExportPrice,
        MappedColumn {
            header: "export_price_per_kwh".to_string(),
            unit: ImportUnit::UsdPerKilowattHour,
        },
    );
    series.insert(
        SeriesKind::Temperature,
        MappedColumn {
            header: "ambient_c".to_string(),
            unit: ImportUnit::Celsius,
        },
    );

    ImportRequest {
        filename: "riverside-works-2024.csv".to_string(),
        timezone: DEMO_TIMEZONE.to_string(),
        interval_minutes: 60,
        // The sample has no gaps, so the strictest policy is also the honest one. A
        // demo that shipped with a permissive gap policy would be teaching the wrong
        // habit on the first screen a user ever sees.
        gap_policy: GapPolicy::Reject,
        mapping: ColumnMapping {
            timestamp: "timestamp".to_string(),
            series,
            demand_period: Some("demand_period".to_string()),
            ignore_columns: Vec::new(),
        },
    }
}

fn tariff() -> TariffSpec {
    let mut demand = BTreeMap::new();
    demand.insert("on-peak".to_string(), 18.50);
    demand.insert("off-peak".to_string(), 4.20);
    TariffSpec {
        // Time-of-use is expressed as data, not as a schedule language: the price is
        // in the CSV, interval by interval.
        import: RateSource::Series,
        export: RateSource::Series,
        import_price_multiplier: 1.0,
        export_price_multiplier: 1.0,
        demand_prices_per_kw_month_usd: demand,
        fixed_charge_usd_per_month: 145.0,
    }
}

