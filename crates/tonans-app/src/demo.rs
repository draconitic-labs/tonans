fn economics() -> EconomicsSpec {
    EconomicsSpec {
        capex_usd: 220_000.0,
        annual_opex_usd: 2_000.0,
        horizon_years: 15,
        discount_rate_pct_per_year: 7.0,
        energy_price_escalation_pct_per_year: 2.5,
        replacement: Some(ReplacementSpec {
            cost_usd: 120_000.0,
            trigger_capacity_pct: 70.0,
        }),
    }
}

fn degradation() -> DegradationSpec {
    DegradationSpec {
        calendar_fade_pct_per_year: 1.8,
        cycle_fade_pct_per_cycle: 0.0035,
        throughput_cost_per_kwh_throughput_usd: 0.008,
        benefit_scaling: BenefitScaling::ProportionalToUsableCapacity,
    }
}

/// A twelve-hour summer outage, on a working day, starting mid-morning.
///
/// Chosen because it is the case a battery is *supposed* to be good at and still
/// might not survive: the afternoon cooling load is at its highest exactly when the
/// array is producing, so the reserve is doing real work.
fn outage() -> OutageSpec {
    OutageSpec {
        windows: vec![OutageWindow {
            start_utc: "2024-07-16T14:00:00Z".parse().expect("a valid instant"),
            end_utc: "2024-07-17T02:00:00Z".parse().expect("a valid instant"),
            label: "Summer storm — 12 h, weekday".to_string(),
        }],
    }
}

fn baseline() -> Scenario {
    Scenario {
        id: "baseline".to_string(),
        name: "Baseline — no storage".to_string(),
        battery: None,
        inverter: InverterSpec {
            battery_power_kw: 0.0,
            site_export_limit_kw: Some(100.0),
        },
        dispatch: DispatchPolicy::SelfConsumption,
        tariff: tariff(),
        economics: EconomicsSpec {
            capex_usd: 0.0,
            annual_opex_usd: 0.0,
            ..economics()
        },
        degradation: degradation(),
        outage: outage(),
        initial_soc_pct: 0.0,
        initial_capacity_pct: 100.0,
    }
}

